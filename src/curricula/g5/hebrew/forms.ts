const UNIT = 'forms';

/** Accepted ways to type a root: "כתב", "כ.ת.ב", "כ-ת-ב", "כ ת ב", and with a final letter at the end ("הלך"). */
export function rootAnswers(root: string): string[] {
  const FINAL: Record<string, string> = { כ: 'ך', מ: 'ם', נ: 'ן', פ: 'ף', צ: 'ץ' };
  const letters = [...root];
  const last = letters[letters.length - 1];
  const forms = [letters];
  if (FINAL[last]) forms.push([...letters.slice(0, -1), FINAL[last]]);
  return forms.flatMap((ls) => ['', '.', '-', ' ', ', ', '׳'].map((sep) => ls.join(sep)));
}

